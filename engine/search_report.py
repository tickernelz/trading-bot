"""Render the round 1 search outputs into docs/strategy-research/results.md and a compact summary JSON."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from engine import search_plan as plan


def pct(value: float | None, digits: int = 2, sign: bool = True) -> str:
    if value is None:
        return "-"
    return f"{value * 100:+.{digits}f}%" if sign else f"{value * 100:.{digits}f}%"


def num(value: float | None, digits: int = 2) -> str:
    return "-" if value is None else f"{value:.{digits}f}"


def ci(values: list[float] | None) -> str:
    return "-" if not values else f"{pct(values[0])} .. {pct(values[1])}"


def summary_row(summary: dict) -> list[str]:
    return [
        str(summary.get("trades", 0)),
        pct(summary.get("win_rate"), 1, sign=False),
        pct(summary.get("wilson_lower"), 1, sign=False),
        pct(summary.get("mean"), 3),
        ci(summary.get("ci95")),
        num(summary.get("profit_factor")),
        num(summary.get("payoff_ratio")),
        pct(summary.get("largest_loss")),
        pct(summary.get("worst5_mean")),
        pct(summary.get("max_drawdown"), 1, sign=False),
        rupiah(summary.get("worst_month_idr")),
        num(summary.get("trades_per_month"), 1),
    ]


def rupiah(value: float | None) -> str:
    return "-" if value is None else f"Rp {value:,.0f}"


SUMMARY_HEAD = [
    "Trades",
    "Win rate",
    "Wilson low",
    "Mean net",
    "95% CI",
    "PF",
    "Payoff",
    "Largest loss",
    "Worst 5 mean",
    "Max DD",
    "Worst month (Rp 2M)",
    "Trades/month",
]


def table(head: list[str], rows: list[list[str]]) -> str:
    lines = ["| " + " | ".join(head) + " |", "| " + " | ".join("---" for _ in head) + " |"]
    lines += ["| " + " | ".join(row) + " |" for row in rows]
    return "\n".join(lines)


def checks_cell(checks: dict) -> str:
    return "".join(
        letter if checks[key] else "-"
        for letter, key in (("a", "a_win_rate"), ("b", "b_folds"), ("c", "c_rolling"), ("d", "d_regimes"))
    )


def walk_forward_section(wf: dict) -> tuple[str, list[dict]]:
    compact = []
    rows = []
    ordered = sorted(
        wf["results"],
        key=lambda entry: (entry["wf_tier"]["tier"], -(entry["costs"][plan.PRIMARY_COST]["all"].get("mean") or -9)),
    )
    for entry in ordered:
        primary = entry["costs"][plan.PRIMARY_COST]
        checks = entry["wf_checks"]
        folds = [checks["fold_win_rates"].get(name) for name, _, _ in plan.FOLDS]
        compact.append(
            {
                "id": entry["id"],
                "family": entry["family"],
                "deployable": entry["deployable"],
                "tier": entry["wf_tier"]["tier"],
                "checks": checks_cell(checks),
                "all": primary["all"],
                "fold_win_rates": checks["fold_win_rates"],
                "fold_std": checks["fold_std"],
                "regimes": checks["regimes"][0],
                "sensitivity": {name: entry["costs"][name]["all"].get("mean") for name in plan.COSTS},
            }
        )
        rows.append(
            [
                entry["id"],
                entry["wf_tier"]["tier"],
                checks_cell(checks),
                *summary_row(primary["all"]),
                " ".join("-" if rate is None else f"{rate * 100:.0f}" for rate in folds),
                num(None if checks["fold_std"] is None else checks["fold_std"] * 100, 1),
                pct(entry["costs"]["stress_041"]["all"].get("mean"), 3),
                pct(entry["costs"]["slip_010"]["all"].get("mean"), 3),
                "yes" if entry["deployable"] else "no",
            ]
        )
    head = [
        "Config",
        "Tier",
        "Target a-d",
        *SUMMARY_HEAD,
        "Fold WR % F1..F8",
        "Fold SD pt",
        "Mean at 0.41%",
        "Mean +0.10% slip",
        "Deployable",
    ]
    return table(head, rows), compact


def regimes_table(regimes: dict) -> str:
    return table(
        ["Regime", *SUMMARY_HEAD],
        [[name, *summary_row(summary)] for name, summary in sorted(regimes.items())],
    )


def render(
    wf: dict, controls: dict, holdout: dict | None, validation: dict | None, final_label: str = "Holdout"
) -> tuple[str, dict]:
    pairs = wf.get("pairs") or list(plan.ROUND1_PAIRS)
    parts = [f"# Strategy search, round {wf.get('round', 1)}: generated results", ""]
    parts.append(
        "Generated by `python -m engine.search_report` from the run outputs; nothing below is typed by hand. "
        "Costs: Indodax taker, buy 0.20555%, sell 0.41555%. A win is a trade with net profit above zero."
    )
    if validation:
        sim, ft = validation["simulator"], validation["stage2_freqtrade"]
        parts += [
            "",
            "## Simulator validation against stage 2 Freqtrade",
            "",
            table(
                ["Source", "Period", "Trades", "Mean net", "Win rate", "Max DD"],
                [
                    [
                        "Freqtrade, stage 2 report",
                        " .. ".join(validation["period"]),
                        str(ft["trades"]),
                        pct(ft["mean"], 3),
                        pct(ft["win_rate"], 1, sign=False),
                        "40.06%",
                    ],
                    [
                        "Simulator",
                        " .. ".join(validation["period"]),
                        str(sim["trades"]),
                        pct(sim["mean"], 3),
                        pct(sim["win_rate"], 1, sign=False),
                        pct(sim["max_drawdown"], 2, sign=False),
                    ],
                ],
            ),
        ]
    wf_table, compact = walk_forward_section(wf)
    parts += [
        "",
        f"## Walk-forward {wf['period'][0][:10]} .. {wf['period'][1][:10]}: {wf['candidates']} configurations",
        "",
        "Target letters: a = win rate >= 60% with >= 100 trades on >= 2 pairs and Wilson lower bound >= 50%; "
        "b = every fold >= 50% and fold SD <= 8 points; c = rolling 30-trade minimum >= 40%; "
        "d = every regime with >= 20 trades >= 50%. A dash marks a failed check.",
        "",
        wf_table,
        "",
        f"Eligible for default: {len(wf['eligible'])}. Selected by the locked rule: `{wf['selected']}`.",
    ]
    selected = next((entry for entry in wf["results"] if entry["id"] == wf["selected"]), None)
    if selected and "ci_low_adjusted" in selected["wf_tier"]:
        tier = selected["wf_tier"]
        parts += [
            "",
            f"Selected walk-forward tier {tier['tier']}: bootstrap CI lower bound {pct(tier['ci_low'], 3)}, "
            f"Bonferroni lower bound over {tier['trials']} cumulative configurations {pct(tier['ci_low_adjusted'], 3)}.",
        ]
    null = wf.get("selected_null")
    if null:
        parts += [
            "",
            f"Null for the selected configuration on the walk-forward ({null['shuffles']} random-entry series, same exits, same entry rate): "
            f"mean p50 {pct(null['mean_p50'], 3)}, p95 {pct(null['mean_p95'], 3)}; win rate p50 {pct(null['win_rate_p50'], 1, sign=False)}, "
            f"p95 {pct(null['win_rate_p95'], 1, sign=False)}; median {null['trades_median']:.0f} trades.",
        ]
    process = wf.get("selection_process") or []
    if process:
        parts += [
            "",
            "## Selection walked forward",
            "",
            "Before each fold, pick the deployable configuration with the best mean on all earlier folds (at least 30 trades), then score it on that fold.",
            "",
            table(
                ["Fold", "Picked", "Earlier mean", "Fold trades", "Fold mean", "Fold win rate"],
                [
                    [
                        row["fold"],
                        row["picked"],
                        pct(row["in_sample_mean"], 3),
                        str(row["fold_trades"]),
                        pct(row["fold_mean"], 3),
                        pct(row["fold_win_rate"], 1, sign=False),
                    ]
                    for row in process
                ],
            ),
        ]
    bh = wf["buy_and_hold"][plan.PRIMARY_COST]
    parts += [
        "",
        "## Buy and hold per fold (net of one buy and one sell)",
        "",
        table(
            ["Window", *pairs],
            [[name, *(pct(values.get(pair), 1) for pair in pairs)] for name, values in bh.items()],
        ),
    ]
    parts += [
        "",
        f"## Lookahead controls ({len(controls['cuts'])} cut points)",
        "",
        "shift: every entry and exit signal moved 1 hour or 1 rule candle earlier (the rule sees the future). "
        "peek: entries kept only when their fill candle closes green. truncation: signals of the last 48 candles at each cut equal those on full data. "
        "live window: entries from the last 649 candles per timeframe equal entries from full history.",
        "",
        table(
            [
                "Config",
                "Honest mean",
                "Honest WR",
                "shift 1h mean",
                "shift tf mean",
                "peek mean",
                "peek WR",
                "Truncation failures",
                "Live-window mismatches",
            ],
            [
                [
                    row["id"],
                    pct(row["honest"]["mean"], 3),
                    pct(row["honest"]["win_rate"], 1, sign=False),
                    pct(row["shift_1h"]["mean"], 3),
                    pct(row["shift_tf"]["mean"], 3),
                    pct(row["peek_next_close"]["mean"], 3),
                    pct(row["peek_next_close"]["win_rate"], 1, sign=False),
                    f"{row['truncation_failures']}/{row['truncation_cuts']}",
                    f"{row['live_window_entry_mismatches']}/{row['truncation_cuts']}",
                ]
                for row in controls["results"]
            ],
        ),
    ]
    if holdout:
        primary = holdout["costs"][plan.PRIMARY_COST]
        checks = holdout["checks"]
        parts += [
            "",
            f"## {final_label} {holdout['period'][0][:10]} .. {holdout['period'][1][:10]}: `{holdout['candidate']}`, "
            + (
                f"tier {holdout['tier']}"
                if final_label == "Holdout"
                else "supporting evidence, not the final evaluation"
            ),
            "",
            table(
                ["Costs", *SUMMARY_HEAD], [[name, *summary_row(cost["all"])] for name, cost in holdout["costs"].items()]
            ),
            "",
            f"Target checks: a {checks['a_win_rate']}, b {checks['b_folds']}, c {checks['c_rolling']}, d {checks['d_regimes']}; "
            f"rolling 30-trade minimum walk-forward / {final_label.lower()}: {', '.join(pct(v, 1, sign=False) for v in checks['rolling30_min'])}. "
            f"Null p95 of the mean {pct(holdout['null']['mean_p95'], 3)} (p50 {pct(holdout['null']['mean_p50'], 3)}), beaten: {holdout['null_beaten']}.",
            "",
            "Per pair:",
            "",
            table(
                ["Pair", *SUMMARY_HEAD],
                [[pair, *summary_row(summary)] for pair, summary in sorted(primary["pairs"].items())],
            ),
            "",
            "Per regime:",
            "",
            regimes_table(primary["regimes"]),
            "",
            f"Comparators on the {final_label.lower()}:",
            "",
            table(
                ["Comparator", *SUMMARY_HEAD],
                [["K-SwingEmaRsi", *summary_row(holdout["comparators"]["K-SwingEmaRsi"])]],
            ),
            "",
            table(
                ["Buy and hold", *holdout["comparators"]["K-buy-and-hold"]],
                [
                    [
                        final_label.lower(),
                        *(pct(value, 1) for value in holdout["comparators"]["K-buy-and-hold"].values()),
                    ]
                ],
            ),
        ]
    compact_out = {"selected": wf["selected"], "eligible": wf["eligible"], "results": compact, "selected_null": null}
    return "\n".join(parts) + "\n", compact_out


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(prog="python -m engine.search_report", description=__doc__)
    parser.add_argument("--out", required=True, type=Path, help="directory with the run outputs")
    parser.add_argument("--docs", required=True, type=Path)
    args = parser.parse_args(argv)

    def load(name: str) -> dict | None:
        path = args.out / name
        return json.loads(path.read_text(encoding="utf-8")) if path.exists() else None

    presample = load("presample.json")
    final, label = (presample, "Pre-sample") if presample else (load("holdout.json"), "Holdout")
    text, compact = render(load("walk-forward.json"), load("controls.json"), final, load("validate.json"), label)
    args.docs.mkdir(parents=True, exist_ok=True)
    (args.docs / "results.md").write_text(text, encoding="utf-8")
    (args.docs / "walk-forward-summary.json").write_text(json.dumps(compact, indent=1), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
